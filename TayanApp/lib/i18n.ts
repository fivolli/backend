const DICTS: Record<AppLang, Dict> = { ru: RU, en: EN, kg: KG };

export function t(lang: AppLang, key: string, params?: Record<string, string | number>): string {
  const dict = DICTS[lang] || RU;
  const base = dict[key] ?? RU[key] ?? key;
  if (!params) return base;
  return base.replace(/\{(\w+)\}/g, (_, name: string) => {
    const v = params[name];
    return v === undefined || v === null ? `{${name}}` : String(v);
  });
}

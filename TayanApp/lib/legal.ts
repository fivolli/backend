function normalizeLang(lang: AppLang): AppLang {
  return lang === 'en' || lang === 'kg' || lang === 'ru' ? lang : 'ru';
}

export function getLegalDoc(kind: LegalDocKind, lang: AppLang): LegalDoc {
  const l = normalizeLang(lang);
  if (kind === 'policy') {
    return l === 'en' ? POLICY_EN : l === 'kg' ? POLICY_KG : POLICY_RU;
  }
  return l === 'en' ? TERMS_EN : l === 'kg' ? TERMS_KG : TERMS_RU;
}
